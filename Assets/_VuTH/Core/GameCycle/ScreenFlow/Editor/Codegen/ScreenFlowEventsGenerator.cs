using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using _VuTH.Core.GameCycle.ScreenFlow.Profile;
using UnityEditor;
using UnityEngine;

namespace _VuTH.Core.GameCycle.ScreenFlow.Editor.Codegen
{
    /// <summary>
    /// Generates <c>Core.Generated.ScreenFlowEvents</c>: one <c>const string</c> per event name used in the
    /// ScreenFlow graph, so game code calls <c>Trigger(ScreenFlowEvents.BootstrapCompleted)</c> and a renamed or
    /// misspelled event becomes a compile error instead of a silent no-op.
    /// </summary>
    public static class ScreenFlowEventsGenerator
    {
        public const string OutputFolder = "Assets/Game/Scripts/Generated";
        public const string OutputFileName = "ScreenFlowEvents.cs";
        public const string Namespace = "Core.Generated";
        public const string ClassName = "ScreenFlowEvents";

        [MenuItem("VuTH/Core/Screen Flow/Generate Event Constants")]
        public static void GenerateFromProfile()
        {
            if (!ScreenFlowProfileUtilities.TryGetProfile(out var profile) || !profile.Graph)
            {
                Debug.LogError("[ScreenFlowEventsGenerator] No ScreenFlowProfile / graph found.");
                return;
            }

            Generate(profile.Graph);
        }

        /// <summary>Writes the constants file for <paramref name="graph"/>. Returns false when it was already up to date.</summary>
        public static bool Generate(ScreenFlowGraph graph)
        {
            var source = BuildSource(CollectEvents(graph));
            var path = Path.Combine(OutputFolder, OutputFileName).Replace('\\', '/');

            if (File.Exists(path) && File.ReadAllText(path) == source)
            {
                Debug.Log($"[ScreenFlowEventsGenerator] {path} is up to date.");
                return false;
            }

            Directory.CreateDirectory(OutputFolder);
            File.WriteAllText(path, source);
            AssetDatabase.ImportAsset(path);
            Debug.Log($"[ScreenFlowEventsGenerator] Wrote {path}.");
            return true;
        }

        /// <summary>Distinct, non-empty event names of the graph mapped to the "From → To" descriptions using them.</summary>
        public static SortedDictionary<string, List<string>> CollectEvents(ScreenFlowGraph graph)
        {
            var result = new SortedDictionary<string, List<string>>(StringComparer.Ordinal);
            if (!graph || graph.Transitions == null) return result;

            var screenNameByGuid = new Dictionary<string, string>(StringComparer.Ordinal);
            if (graph.Nodes != null)
            {
                foreach (var node in graph.Nodes)
                {
                    if (node == null || string.IsNullOrEmpty(node.Guid)) continue;
                    screenNameByGuid[node.Guid] = node.Screen ? node.Screen.name : "<no screen>";
                }
            }

            foreach (var t in graph.Transitions)
            {
                if (t == null || string.IsNullOrWhiteSpace(t.EventName)) continue;

                if (!result.TryGetValue(t.EventName, out var usages))
                {
                    usages = new List<string>();
                    result[t.EventName] = usages;
                }

                var from = screenNameByGuid.TryGetValue(t.FromNodeGuid ?? "", out var f) ? f : "?";
                var to = screenNameByGuid.TryGetValue(t.ToNodeGuid ?? "", out var to2) ? to2 : "?";
                usages.Add(t.Navigation == ScreenFlowNavigation.Enter ? $"{from} → {to}" : $"{from} → {to} ({t.Navigation})");
            }

            return result;
        }

        public static string BuildSource(IReadOnlyDictionary<string, List<string>> events)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by ScreenFlowEventsGenerator (VuTH > Core > Screen Flow > Generate Event Constants).");
            sb.AppendLine("// Do not edit by hand: regenerate after changing event names in the ScreenFlow graph.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine($"namespace {Namespace}");
            sb.AppendLine("{");
            sb.AppendLine($"    public static class {ClassName}");
            sb.AppendLine("    {");

            var usedIdentifiers = new HashSet<string>(StringComparer.Ordinal) { "All" };
            foreach (var pair in events)
            {
                var identifier = MakeUnique(ToIdentifier(pair.Key), usedIdentifiers);
                var usages = pair.Value == null || pair.Value.Count == 0 ? "" : string.Join(", ", pair.Value);
                sb.AppendLine($"        /// <summary>{EscapeXml(usages)}</summary>");
                sb.AppendLine($"        public const string {identifier} = \"{EscapeString(pair.Key)}\";");
                sb.AppendLine();
            }

            sb.AppendLine("        /// <summary>Every event name used by the graph.</summary>");
            sb.Append("        public static readonly string[] All = { ");
            sb.Append(string.Join(", ", events.Keys.Select(k => $"\"{EscapeString(k)}\"")));
            sb.AppendLine(" };");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        /// <summary>
        /// "bootstrap completed" / "bootstrap_completed" / "BootstrapCompleted" → <c>BootstrapCompleted</c>.
        /// Invalid characters are dropped and a leading digit gets an underscore prefix. The result is PascalCase, so it
        /// can never collide with a (lower-case) C# keyword.
        /// </summary>
        public static string ToIdentifier(string eventName)
        {
            var sb = new StringBuilder();
            var upperNext = true;
            foreach (var ch in eventName ?? string.Empty)
            {
                if (char.IsLetterOrDigit(ch))
                {
                    sb.Append(upperNext ? char.ToUpperInvariant(ch) : ch);
                    upperNext = false;
                }
                else
                {
                    upperNext = true; // separators (space, _, -, .) start a new word
                }
            }

            if (sb.Length == 0) return "_";
            if (char.IsDigit(sb[0])) sb.Insert(0, '_');

            return sb.ToString();
        }

        private static string MakeUnique(string identifier, HashSet<string> used)
        {
            var candidate = identifier;
            for (var i = 2; !used.Add(candidate); i++) candidate = identifier + i;
            return candidate;
        }

        private static string EscapeString(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");

        private static string EscapeXml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
    }
}
